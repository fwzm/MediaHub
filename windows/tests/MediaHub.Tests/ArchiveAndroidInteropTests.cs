using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using MediaHub.Sync;
using Xunit;

namespace MediaHub.Tests;

/// <summary>
/// Pins the reverse interoperability direction of the encrypted offline archive (W6-65): the bytes are written
/// by the Android Kotlin <c>ArchiveWriter</c> and must be read by this build exactly as written.
/// </summary>
/// <remarks>
/// <para>
/// The asset is a real file produced by <c>ArchiveWriter.write</c> in the Android core module, committed as a
/// golden file. It is deliberately not regenerated by the test suite: the salt and nonce are random per write,
/// so only a fixed file can pin the exact payload bytes the other implementation produced.
/// </para>
/// <para>
/// What this proves that the same-language round-trip tests cannot: the Kotlin writer omits absent optional
/// properties, keeps unknown <c>sourceType</c> values verbatim, and orders the document fields so that the
/// Windows reader — and the Windows writer, once it re-serialises — agree without a translation layer.
/// </para>
/// </remarks>
public sealed class ArchiveAndroidInteropTests
{
    private const string Passphrase = "correct horse battery staple";

    private const string OtherPassphrase = "a different long passphrase";

    private const string Magic = "MHSYNCA1";

    /// <summary>Byte length of the committed golden archive.</summary>
    private const int ArchiveLength = 1164;

    /// <summary>SHA-256 of the committed golden archive.</summary>
    private const string ArchiveSha256 = "72365f67b240b10aa20c3c5f867f53600199ac5eb9a834e0ebe672d8d6794a15";

    /// <summary>Header bytes are 161 UTF-8 bytes; the rest of the prefix is the 12-byte magic and length.</summary>
    private const int HeaderLength = 161;
    private const int TrailerLength = 12 + 161;

    /// <summary>SHA-256 of the decrypted payload; pins the exact JSON the Kotlin writer emitted.</summary>
    private const string PayloadSha256 = "68957f0d6658058139b861d86c868b64364cf7011adb7189851d5ebd40e16b79";

    private const int PayloadLength = 975;

    /// <summary>Header JSON exactly as the Kotlin writer serialised it (fixed field order, no whitespace).</summary>
    private const string HeaderJson =
        "{\"version\":1,\"kdf\":\"pbkdf2-sha256\",\"iterations\":600000," +
        "\"saltBase64\":\"rk4gfF2NEFUQih+xagtPDQ==\",\"nonceBase64\":\"Jnfcf+l0U161FUBq\"," +
        "\"createdAtEpochMs\":1700000000000}";

    private static string ArchivePath =>
        Path.Combine(AppContext.BaseDirectory, "assets", "android-written-archive.mharchive");

    [Fact]
    public void The_android_written_archive_is_read_field_by_field()
    {
        byte[] archive = ReadArchive();

        SourceSyncEnvelope envelope = EncryptedArchiveReader.Read(archive, Passphrase);

        Assert.Equal(SourceSyncEnvelope.CurrentSchemaVersion, envelope.SchemaVersion);
        Assert.Equal(SourceSyncEnvelope.CurrentSchemaVersion, envelope.MinimumReaderVersion);
        Assert.Equal("device-android-pixel", envelope.DeviceId);
        Assert.Equal("0123456789abcdef0123456789abcdef", envelope.SnapshotId);
        Assert.Equal(1_700_000_000_000, envelope.CreatedAtEpochMs);
        Assert.False(envelope.Capabilities.CanSendSecrets);
        Assert.Equal(["emby", "jellyfin", "webdav"], envelope.Capabilities.SourceTypes);

        Assert.Equal(2, envelope.Sources.Count);

        SourceRecord livingRoom = envelope.Sources[0];
        Assert.Equal("0f9a1c2e-1111-4a2b-9c3d-000000000001", livingRoom.SyncSourceId);
        Assert.Equal("emby", livingRoom.SourceType.Raw);
        Assert.Equal("emby", livingRoom.SourceType.Wire);
        Assert.True(livingRoom.SourceType.IsKnown);
        Assert.Equal("家庭 NAS（客厅）", livingRoom.DisplayName);
        Assert.Equal("张三", livingRoom.AccountScope);
        Assert.Equal(42, livingRoom.RecordRevision);
        Assert.Equal(3, livingRoom.FieldVersion);
        Assert.Null(livingRoom.Secrets);

        Assert.Equal(2, livingRoom.Endpoints.Count);
        Assert.Equal("http://192.168.1.20:8096/emby", livingRoom.Endpoints[0].Url);
        Assert.True(livingRoom.Endpoints[0].IsPrimary);
        Assert.True(livingRoom.Endpoints[0].Enabled);
        Assert.Equal(0, livingRoom.Endpoints[0].SortOrder);
        Assert.Equal("https://nas.example.invalid/emby", livingRoom.Endpoints[1].Url);
        Assert.False(livingRoom.Endpoints[1].IsPrimary);
        Assert.False(livingRoom.Endpoints[1].Enabled);
        Assert.Equal(2, livingRoom.Endpoints[1].SortOrder);

        SourceRecord shelf = envelope.Sources[1];
        Assert.Equal("0f9a1c2e-2222-4a2b-9c3d-000000000002", shelf.SyncSourceId);
        Assert.Equal("Backup shelf", shelf.DisplayName);
        Assert.Null(shelf.AccountScope);
        Assert.Equal(7, shelf.RecordRevision);
        Assert.Equal(1, shelf.FieldVersion);
        Assert.Null(shelf.Secrets);
        Assert.Single(shelf.Endpoints);
        Assert.Equal("acme://shelf-one", shelf.Endpoints[0].Url);

        Tombstone deletion = Assert.Single(envelope.Deletions);
        Assert.Equal("0f9a1c2e-3333-4a2b-9c3d-000000000003", deletion.SyncSourceId);
        Assert.Equal(1_760_000_000_000, deletion.DeletedAtEpochMs);
        Assert.Equal(5, deletion.RecordRevision);
    }

    [Fact]
    public void An_unknown_source_type_is_carried_through_untouched()
    {
        SourceRecord shelf = EncryptedArchiveReader.Read(ReadArchive(), Passphrase).Sources[1];

        Assert.Equal("acme-nas", shelf.SourceType.Raw);
        Assert.Equal("acme-nas", shelf.SourceType.Wire);
        Assert.False(shelf.SourceType.IsKnown);
        Assert.False(SyncSourceTypes.IsKnown(shelf.SourceType.Wire));
    }

    [Fact]
    public void The_android_written_archive_bytes_are_pinned()
    {
        byte[] archive = ReadArchive();

        Assert.Equal(ArchiveLength, archive.Length);
        Assert.Equal(ArchiveSha256, Convert.ToHexStringLower(SHA256.HashData(archive)));
        Assert.Equal(Magic, Encoding.ASCII.GetString(archive, 0, 8));
        Assert.Equal(HeaderLength, BinaryPrimitives.ReadInt32BigEndian(archive.AsSpan(8, 4)));
    }

    [Fact]
    public void The_android_header_matches_the_canonical_shape()
    {
        byte[] archive = ReadArchive();

        ArchiveHeader header = EncryptedArchiveReader.ReadHeader(archive);

        Assert.Equal(ArchiveHeader.CurrentVersion, header.Version);
        Assert.Equal(ArchiveKdf.Pbkdf2Sha256Name, header.Kdf);
        Assert.Equal(ArchiveKdf.DefaultIterations, header.Iterations);
        Assert.Equal(1_700_000_000_000, header.CreatedAtEpochMs);
        Assert.Equal(ArchiveKdf.SaltSize, Convert.FromBase64String(header.SaltBase64).Length);
        Assert.Equal(ArchiveHeader.NonceSize, Convert.FromBase64String(header.NonceBase64).Length);

        byte[] headerBytes = archive.AsSpan(12, HeaderLength).ToArray();
        Assert.Equal(HeaderJson, Encoding.UTF8.GetString(headerBytes));

        // The Windows codec must accept the Kotlin header and give back the same values. Byte-for-byte
        // re-serialisation is deliberately NOT asserted: System.Text.Json escapes "+" as "\u002B" while
        // kotlinx.serialization writes it raw, so the salt of this file differs textually between the two
        // writers. That is harmless — GCM authenticates the header bytes found on disk, never a re-encoding —
        // and both readers parse the escaped form, so the contract is "same values", not "same bytes".
        Assert.True(ArchiveHeaderCodec.TryParse(ArchiveHeaderCodec.Serialize(header), out ArchiveHeader? reparsed, out string? headerError));
        Assert.Null(headerError);
        Assert.Equal(header, reparsed);
    }

    [Fact]
    public void The_windows_serializer_reproduces_the_kotlin_document_semantically()
    {
        byte[] archive = ReadArchive();
        ArchiveHeader header = EncryptedArchiveReader.ReadHeader(archive);

        byte[] payload = DecryptPayload(archive, header, Passphrase);
        Assert.Equal(PayloadLength, payload.Length);
        Assert.Equal(PayloadSha256, Convert.ToHexStringLower(SHA256.HashData(payload)));

        string kotlinJson = Encoding.UTF8.GetString(payload);
        SourceSyncEnvelope fromKotlin = SourceSyncCodec.Deserialize(kotlinJson);
        SourceSyncEnvelope fromReader = EncryptedArchiveReader.Read(archive, Passphrase);
        Assert.Equal(SourceSyncCodec.Serialize(fromReader), SourceSyncCodec.Serialize(fromKotlin));

        // Field order and the absence of whitespace differ only in escaping of non-ASCII text, so compare
        // the parsed trees rather than the raw strings.
        JsonNode? kotlinTree = JsonNode.Parse(kotlinJson);
        JsonNode? windowsTree = JsonNode.Parse(SourceSyncCodec.Serialize(fromReader));
        Assert.True(JsonNode.DeepEquals(kotlinTree, windowsTree));

        // The Windows writer must accept what the Kotlin writer produced without a translation step, and
        // re-reading its own output must produce the same document (canonical form is a fixed point).
        string canonical = SourceSyncCodec.Serialize(fromReader);
        Assert.Equal(canonical, SourceSyncCodec.Serialize(SourceSyncCodec.Deserialize(canonical)));
    }

    [Fact]
    public void A_wrong_passphrase_is_indistinguishable_from_tampering()
    {
        byte[] archive = ReadArchive();

        Assert.False(EncryptedArchiveReader.TryRead(archive, OtherPassphrase, out SourceSyncEnvelope? envelope, out string? wrongPassphrase));
        Assert.Null(envelope);
        Assert.Equal(ArchiveError.WrongPassphraseOrTampered, wrongPassphrase);

        byte[] tamperedHeader = WithHeaderText(archive, "1700000000000", "1700000000001");
        Assert.False(EncryptedArchiveReader.TryRead(tamperedHeader, Passphrase, out _, out string? tamperedHeaderReason));
        Assert.Equal(ArchiveError.WrongPassphraseOrTampered, tamperedHeaderReason);

        byte[] tamperedCiphertext = (byte[])archive.Clone();
        tamperedCiphertext[tamperedCiphertext.Length - ArchiveHeader.TagSize - 1] ^= 0x5A;
        Assert.False(EncryptedArchiveReader.TryRead(tamperedCiphertext, Passphrase, out _, out string? tamperedCipherReason));
        Assert.Equal(ArchiveError.WrongPassphraseOrTampered, tamperedCipherReason);

        // The three outcomes must be literally the same message, or an attacker learns which one happened.
        ArchiveException fromRead = Assert.Throws<ArchiveException>(() => EncryptedArchiveReader.Read(tamperedCiphertext, Passphrase));
        Assert.Equal(ArchiveError.WrongPassphraseOrTampered, fromRead.Reason);
        Assert.Equal(
            "The archive could not be decrypted: the passphrase is wrong or the file has been modified.",
            fromRead.Message);
    }

    [Fact]
    public void A_layout_error_is_reported_before_the_passphrase_is_examined()
    {
        byte[] archive = ReadArchive();

        // Keep the magic and header, drop the whole ciphertext and the tag: the file is structurally empty,
        // so the layout error must win over the (also invalid) empty passphrase.
        byte[] headerOnly = archive.AsSpan(0, TrailerLength).ToArray();

        Assert.False(EncryptedArchiveReader.TryRead(headerOnly, "", out _, out string? reason));
        Assert.Equal(ArchiveError.CorruptCiphertext, reason);

        Assert.False(EncryptedArchiveReader.TryRead(archive, null, out _, out string? noPassphrase));
        Assert.Equal(ArchiveError.PassphraseEmpty, noPassphrase);

        Assert.False(EncryptedArchiveReader.TryRead(archive, "short", out _, out string? weak));
        Assert.Equal(ArchiveError.PassphraseTooWeak, weak);
    }

    [Fact]
    public void The_android_written_archive_carries_no_plaintext()
    {
        byte[] archive = ReadArchive();

        foreach (string needle in new[]
        {
            "家庭 NAS（客厅）",
            "device-android-pixel",
            "0f9a1c2e-1111-4a2b-9c3d-000000000001",
            "张三",
            "acme-nas",
            "shelf-one",
            "schemaVersion",
        })
        {
            Assert.True(
                archive.AsSpan().IndexOf(Encoding.UTF8.GetBytes(needle)) < 0,
                "The archive leaked the plaintext token: " + needle);
        }
    }

    private static byte[] ReadArchive() => File.ReadAllBytes(ArchivePath);

    private static byte[] DecryptPayload(byte[] archive, ArchiveHeader header, string passphrase)
    {
        byte[] salt = Convert.FromBase64String(header.SaltBase64);
        byte[] nonce = Convert.FromBase64String(header.NonceBase64);
        byte[] key = ArchiveKdf.DeriveKey(passphrase, salt, header.Iterations);

        int cipherOffset = TrailerLength;
        int cipherLength = archive.Length - cipherOffset - ArchiveHeader.TagSize;
        byte[] ciphertext = archive.AsSpan(cipherOffset, cipherLength).ToArray();
        byte[] tag = archive.AsSpan(archive.Length - ArchiveHeader.TagSize, ArchiveHeader.TagSize).ToArray();
        byte[] payload = new byte[cipherLength];

        using var aes = new AesGcm(key, ArchiveHeader.TagSize);
        aes.Decrypt(nonce, ciphertext, tag, payload, archive.AsSpan(0, TrailerLength));
        return payload;
    }

    private static byte[] WithHeaderText(byte[] archive, string from, string to)
    {
        Assert.Equal(from.Length, to.Length);

        byte[] copy = (byte[])archive.Clone();
        string header = Encoding.UTF8.GetString(copy, 12, HeaderLength);
        int index = header.IndexOf(from, StringComparison.Ordinal);
        Assert.True(index >= 0);

        byte[] replacement = Encoding.UTF8.GetBytes(header[..index] + to + header[(index + from.Length)..]);
        Assert.Equal(HeaderLength, replacement.Length);
        replacement.CopyTo(copy, 12);
        return copy;
    }
}
