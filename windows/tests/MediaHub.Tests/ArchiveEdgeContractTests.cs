using System.Text.Json;
using MediaHub.Sync;
using Xunit;

namespace MediaHub.Tests;

/// <summary>
/// Cross-language edge contract (W6-67): whitespace, ASCII case folding, lone surrogates, and the JSON
/// documents each side must refuse.
/// </summary>
/// <remarks>
/// <para>
/// Every answer in this file comes from the vector file, not from a hand-written expectation: the same
/// JSON is consumed by the Android twin <c>com.mediahub.core.common.archive.ArchiveEdgeContractTest</c>, so a
/// deliberate divergence on either side fails one of the two suites instead of shipping.
/// </para>
/// <para>
/// The file is committed at <c>core/common/src/test/resources/archive/windows-archive-vectors.json</c>
/// (Android) and at <c>windows/tests/assets/windows-archive-vectors.json</c> (here) because the C# suite must
/// not read the Android source tree; the two copies are byte-identical, generated by
/// <c>D:/mh-verify/archive-vectors</c>.
/// </para>
/// </remarks>
public sealed class ArchiveEdgeContractTests
{
    private static readonly JsonDocument Vectors = JsonDocument.Parse(
        File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "assets", "windows-archive-vectors.json")));

    private static readonly JsonElement Edges = Vectors.RootElement.GetProperty("edges");

    private static readonly string Passphrase = Vectors.RootElement.GetProperty("passphrase").GetString()!;

    // ------------------------------------------------------------- helpers

    private static JsonElement Entries(string name) => Edges.GetProperty(name);

    private static string TextOf(JsonElement element) => element.GetString()!;

    /// <summary>The vectors store text as UTF-16 code units so a lone surrogate survives the round trip.</summary>
    private static string Utf16Of(JsonElement element)
    {
        int[] units = element.EnumerateArray().Select(item => item.GetInt32()).ToArray();
        char[] characters = new char[units.Length];
        for (int index = 0; index < units.Length; index++)
        {
            characters[index] = (char)units[index];
        }

        return new string(characters);
    }

    private static string? ReasonOf(JsonElement entry, string property) =>
        entry.GetProperty(property).ValueKind == JsonValueKind.Null ? null : TextOf(entry.GetProperty(property));

    private static SourceSyncEnvelope CanonicalEnvelope()
    {
        byte[] archive = Convert.FromBase64String(
            TextOf(Vectors.RootElement.GetProperty("archive").GetProperty("base64")));
        Assert.True(
            EncryptedArchiveReader.TryRead(archive, Passphrase, out SourceSyncEnvelope? envelope, out string? reason),
            "canonical archive must decrypt: " + reason);
        Assert.Null(reason);
        return envelope!;
    }

    // ------------------------------------------------------------- whitespace and case folding

    [Fact]
    public void TheWhitespaceTableIsTheUnicodeWhiteSpacePropertyOfDotNet()
    {
        Assert.Equal(25, WireText.WhitespaceCodePoints.Length);

        // The table exists so both runtimes agree; on .NET it must be exactly char.IsWhiteSpace, for every BMP char.
        List<string> mismatches = [];
        for (int code = 0; code <= 0xFFFF; code++)
        {
            char character = (char)code;
            if (char.IsWhiteSpace(character) != WireText.IsWhitespace(character))
            {
                mismatches.Add("U+" + code.ToString("X4"));
            }
        }

        Assert.Empty(mismatches);

        HashSet<int> expected = Entries("whitespaceCodePoints")
            .EnumerateArray()
            .Select(item => item.GetInt32())
            .ToHashSet();
        Assert.Equal(expected, WireText.WhitespaceCodePoints.ToHashSet());

        // Deliberately not whitespace on either side: record/unit separator, zero-width space, BOM, soft hyphen.
        foreach (int notWhitespace in new[] { 0x001C, 0x001F, 0x200B, 0xFEFF, 0x00AD })
        {
            Assert.False(WireText.IsWhitespace((char)notWhitespace), "U+" + notWhitespace.ToString("X4"));
        }
    }

    [Fact]
    public void IsBlankAndTrimAgreeWithEveryVectorCandidate()
    {
        foreach (JsonElement entry in Entries("blankCandidates").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string text = Utf16Of(entry.GetProperty("utf16"));
            bool blank = entry.GetProperty("blank").GetBoolean();
            Assert.True(blank == WireText.IsBlank(text), name + " (blank)");
            string trimmed = entry.GetProperty("trimmed").ValueKind == JsonValueKind.Null
                ? ""
                : Utf16Of(entry.GetProperty("trimmed"));
            Assert.True(trimmed == WireText.Trim(text), name + " (trim)");
        }
    }

    [Fact]
    public void AsciiCaseFoldingNeverFoldsANonAsciiLookalike()
    {
        foreach (JsonElement entry in Entries("caseFoldPairs").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string left = Utf16Of(entry.GetProperty("left"));
            string right = Utf16Of(entry.GetProperty("right"));
            bool equal = entry.GetProperty("equal").GetBoolean();
            Assert.True(equal == WireText.EqualsAsciiIgnoreCase(left, right), name);
        }

        // The JVM folds U+017F (long s) and U+212A (Kelvin sign) onto ASCII; .NET ordinal comparison must not.
        Assert.False(WireText.EqualsAsciiIgnoreCase("pa" + (char)0x017F + "sword1234", "password1234"));
        Assert.False(WireText.EqualsAsciiIgnoreCase("pbkdf2-" + (char)0x212A + "ha256", "pbkdf2-kha256"));
    }

    [Fact]
    public void LoneSurrogatesAreDetectedByCodeUnitNotByCharacterCount()
    {
        foreach (JsonElement entry in Entries("loneSurrogateCandidates").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string text = Utf16Of(entry.GetProperty("utf16"));
            bool lone = entry.GetProperty("lone").GetBoolean();
            Assert.True(lone == WireText.HasLoneSurrogate(text), name);
        }

        Assert.False(WireText.HasLoneSurrogate(new string(new[] { (char)0xD83D, (char)0xDD12 })));
    }

    // ------------------------------------------------------------- passphrase policy

    [Fact]
    public void ThePassphrasePolicyGivesTheVectorAnswerForEveryCandidate()
    {
        foreach (JsonElement entry in Entries("passphraseCandidates").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string passphrase = Utf16Of(entry.GetProperty("utf16"));
            string? expected = ReasonOf(entry, "reason");
            string? actual = ArchivePassphrase.TryValidate(passphrase, out string? reason) ? null : reason;
            Assert.True(expected == actual, name + " expected " + (expected ?? "<null>") + " but got " + (actual ?? "<null>"));
        }
    }

    [Fact]
    public void TheWriterRefusesALoneSurrogatePassphraseBeforePbkdf2SeesIt()
    {
        string tail = Passphrase + (char)0xD800;
        Assert.False(ArchivePassphrase.TryValidate(tail, out string? reason));
        Assert.Equal(ArchiveError.PassphraseTooWeak, reason);

        ArchiveException thrown = Assert.Throws<ArchiveException>(() => EncryptedArchiveWriter.Write(CanonicalEnvelope(), tail));
        Assert.Equal(ArchiveError.PassphraseTooWeak, thrown.Reason);
    }

    // ------------------------------------------------------------- kdf names and headers

    [Fact]
    public void KdfNamesAreMatchedWithAsciiFoldingAndTheUnicodeWhitespaceSet()
    {
        foreach (JsonElement entry in Entries("kdfNameCandidates").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string candidate = Utf16Of(entry.GetProperty("utf16"));
            bool accepted = entry.GetProperty("accepted").GetBoolean();
            Assert.True(accepted == ArchiveKdf.TryParse(candidate, out _), name);
        }
    }

    [Fact]
    public void HeaderParsingAndKdfAcceptanceAgreeWithEveryVector()
    {
        foreach (JsonElement entry in Entries("headerVariants").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            byte[] headerBytes = Convert.FromBase64String(TextOf(entry.GetProperty("headerBase64")));
            bool expectedParses = entry.GetProperty("parses").GetBoolean();
            bool parsed = ArchiveHeaderCodec.TryParse(headerBytes, out ArchiveHeader? header, out _);
            Assert.True(expectedParses == parsed, name + " (parse)");

            JsonElement kdfAccepted = entry.GetProperty("kdfAccepted");
            if (parsed && kdfAccepted.ValueKind != JsonValueKind.Null)
            {
                Assert.True(kdfAccepted.GetBoolean() == ArchiveKdf.TryParse(header!.Kdf, out _), name + " (kdf)");
            }

            JsonElement version = entry.GetProperty("version");
            if (parsed && version.ValueKind != JsonValueKind.Null)
            {
                Assert.True(version.GetInt32() == header!.Version, name + " (version)");
            }
        }
    }

    // ------------------------------------------------------------- envelopes

    [Fact]
    public void EnvelopeDecodingReportsTheVectorReasonForEveryVariant()
    {
        foreach (JsonElement entry in Entries("envelopeVariants").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string document = TextOf(entry.GetProperty("document"));
            string? expected = ReasonOf(entry, "reason");

            bool accepted = SourceSyncCodec.TryDeserialize(document, out _, out string? error);
            string? actual = accepted || error is null ? null : error.Split(": ")[0];
            Assert.True(expected == actual, name + " expected " + (expected ?? "<null>") + " but got " + (actual ?? "<null>"));
            Assert.True((expected is null) == accepted, name + " (accepted)");
        }
    }

    [Fact]
    public void EnvelopeWritingRejectsTheDocumentsTheWindowsWriterRejects()
    {
        SourceSyncEnvelope canonical = CanonicalEnvelope();
        foreach (JsonElement entry in Entries("envelopeWriteRejections").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string? expected = ReasonOf(entry, "writeReason");
            SourceSyncEnvelope candidate = name switch
            {
                "device-id-lone-surrogate" => canonical with { DeviceId = "a" + (char)0xD800 + "b" },
                "device-id-next-line-only" => canonical with { DeviceId = ((char)0x0085).ToString() },
                "display-name-lone-surrogate" => canonical with
                {
                    Sources = [canonical.Sources[0] with { DisplayName = "a" + (char)0xD800 + "b" }],
                },
                _ => canonical,
            };

            if (expected is null)
            {
                Assert.Null(Record.Exception(() => SourceSyncCodec.Serialize(candidate)));
            }
            else
            {
                SyncContractException thrown = Assert.Throws<SyncContractException>(
                    () => SourceSyncCodec.Serialize(candidate));
                Assert.True(expected == thrown.Reason, name + " expected " + expected + " but got " + thrown.Reason);
            }
        }
    }

    // ------------------------------------------------------------- archives

    [Fact]
    public void ArchiveReadingAndWritingAgreeOnEveryPassphraseCase()
    {
        byte[] archive = Convert.FromBase64String(
            TextOf(Vectors.RootElement.GetProperty("archive").GetProperty("base64")));
        SourceSyncEnvelope canonical = CanonicalEnvelope();

        foreach (JsonElement entry in Entries("archivePassphraseCases").EnumerateArray())
        {
            string name = TextOf(entry.GetProperty("name"));
            string passphrase = Utf16Of(entry.GetProperty("passphraseUtf16"));
            string? expectedRead = ReasonOf(entry, "readReason");
            string? expectedWrite = ReasonOf(entry, "writeReason");

            EncryptedArchiveReader.TryRead(archive, passphrase, out _, out string? readReason);
            Assert.True(expectedRead == readReason, name + " (read) expected " + (expectedRead ?? "<null>") + " but got " + (readReason ?? "<null>"));

            if (expectedWrite is null)
            {
                Assert.Null(Record.Exception(() => EncryptedArchiveWriter.Write(canonical, passphrase)));
            }
            else
            {
                ArchiveException thrown = Assert.Throws<ArchiveException>(
                    () => EncryptedArchiveWriter.Write(canonical, passphrase));
                Assert.True(expectedWrite == thrown.Reason, name + " (write) expected " + expectedWrite + " but got " + thrown.Reason);
            }
        }
    }
}
