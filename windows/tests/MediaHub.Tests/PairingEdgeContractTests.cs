using System.Text.Json;
using MediaHub.Sync;
using Xunit;

namespace MediaHub.Tests;

/// <summary>
/// Cross-language text edge contract for the pairing side (W6-69): whitespace, ASCII case folding,
/// prefix and ordering comparisons, lone surrogates, and the stable reasons link/payload decoding reports.
/// </summary>
/// <remarks>
/// <para>
/// Every answer here comes from the golden vector file, not from a hand-written expectation: the same JSON is
/// consumed by the Android twin <c>com.mediahub.core.common.pairing.PairingEdgeContractTest</c>, so a deliberate
/// divergence on either side fails one of the two suites instead of shipping.
/// </para>
/// <para>
/// The file is committed at <c>core/common/src/test/resources/pairing/windows-pairing-vectors.json</c> (Android)
/// and at <c>windows/tests/assets/windows-pairing-vectors.json</c> (here); the two copies are byte-identical,
/// generated by <c>D:/mh-verify/pairing-vectors</c>.
/// </para>
/// </remarks>
public sealed class PairingEdgeContractTests
{
    private static readonly JsonDocument Vectors = JsonDocument.Parse(
        File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "assets", "windows-pairing-vectors.json")));

    private static readonly JsonElement Edges = Vectors.RootElement.GetProperty("textEdges");

    // ------------------------------------------------------------- helpers

    private static JsonElement Entries(string name) => Edges.GetProperty(name);

    private static string TextOf(JsonElement element) => element.GetString()!;

    private static string NameOf(JsonElement entry) => TextOf(entry.GetProperty("name"));

    /// <summary>The vectors store text as UTF-16 code units so a lone surrogate survives the round trip.</summary>
    private static string Utf16Of(JsonElement element)
    {
        int[] units = element.EnumerateArray().Select(item => item.GetInt32()).ToArray();
        char[] characters = new char[units.Length];
        for (int index = 0; index < units.Length; index++)
        {
            characters[index] = (char)units[index];
        }

        return new string(characters);
    }

    private static string TextOf(JsonElement entry, string property) => Utf16Of(entry.GetProperty(property));

    private static string? NullableTextOf(JsonElement entry, string property) =>
        entry.GetProperty(property).ValueKind == JsonValueKind.Null ? null : Utf16Of(entry.GetProperty(property));

    // ------------------------------------------------------------- whitespace, case folding, ordering

    [Fact]
    public void TheWhitespaceTableMatchesTheVectorsAndExcludesTheRuntimeExtras()
    {
        HashSet<int> expected = Entries("whitespaceCodePoints")
            .EnumerateArray()
            .Select(item => item.GetInt32())
            .ToHashSet();
        Assert.Equal(25, expected.Count);
        Assert.Equal(expected, WireText.WhitespaceCodePoints.ToHashSet());

        // The table is explicit on both sides: JVM Char.isWhitespace also accepts U+001C-U+001F and rejects U+0085,
        // so a runtime-derived set would diverge even though this host happens to agree with Unicode.
        foreach (int notWhitespace in new[] { 0x001C, 0x001F, 0x200B, 0xFEFF, 0x00AD })
        {
            Assert.False(WireText.IsWhitespace((char)notWhitespace), "U+" + notWhitespace.ToString("X4"));
        }

        Assert.True(WireText.IsWhitespace((char)0x0085));
        Assert.True(WireText.IsWhitespace((char)0x3000));
    }

    [Fact]
    public void IsBlankAndTrimAgreeWithEveryVectorCandidate()
    {
        foreach (JsonElement entry in Entries("blankCandidates").EnumerateArray())
        {
            string name = NameOf(entry);
            string text = TextOf(entry, "utf16");
            bool blank = entry.GetProperty("blank").GetBoolean();
            Assert.True(blank == WireText.IsBlank(text), name + " (blank)");

            string? trimmed = NullableTextOf(entry, "trimmed");
            Assert.True((trimmed ?? "") == WireText.Trim(text), name + " (trim)");
        }
    }

    [Fact]
    public void AsciiCaseFoldingNeverFoldsANonAsciiLookalike()
    {
        foreach (JsonElement entry in Entries("caseFoldPairs").EnumerateArray())
        {
            string name = NameOf(entry);
            string left = TextOf(entry, "left");
            string right = TextOf(entry, "right");
            bool equal = entry.GetProperty("equal").GetBoolean();
            Assert.True(equal == WireText.EqualsAsciiIgnoreCase(left, right), name);
        }
    }

    [Fact]
    public void AsciiCaseTransformsOnlyTouchAsciiLetters()
    {
        foreach (JsonElement entry in Entries("asciiCaseTransforms").EnumerateArray())
        {
            string name = NameOf(entry);
            string text = TextOf(entry, "utf16");
            Assert.True(TextOf(entry, "upper") == WireText.UppercaseAscii(text), name + " (upper)");
            Assert.True(TextOf(entry, "lower") == WireText.LowercaseAscii(text), name + " (lower)");
        }
    }

    [Fact]
    public void PrefixTestFoldsAsciiOnly()
    {
        foreach (JsonElement entry in Entries("prefixPairs").EnumerateArray())
        {
            string name = NameOf(entry);
            string value = TextOf(entry, "value");
            string prefix = TextOf(entry, "prefix");
            bool expected = entry.GetProperty("result").GetBoolean();
            Assert.True(expected == WireText.StartsWithAsciiIgnoreCase(value, prefix), name);
        }
    }

    [Fact]
    public void ComparisonIsATotalOrderThatFoldsAsciiOnly()
    {
        foreach (JsonElement entry in Entries("comparePairs").EnumerateArray())
        {
            string name = NameOf(entry);
            string left = TextOf(entry, "left");
            string right = TextOf(entry, "right");
            int expected = entry.GetProperty("sign").GetInt32();
            int forward = WireText.CompareAsciiIgnoreCase(left, right);
            Assert.True(expected == Math.Sign(forward), name);
            Assert.True(WireText.CompareAsciiIgnoreCase(right, left) == -forward, name + " (antisymmetric)");
        }
    }

    [Fact]
    public void LoneSurrogateDetectionMatchesEveryCandidate()
    {
        foreach (JsonElement entry in Entries("loneSurrogateCandidates").EnumerateArray())
        {
            string name = NameOf(entry);
            bool expected = entry.GetProperty("lone").GetBoolean();
            Assert.True(expected == WireText.HasLoneSurrogate(TextOf(entry, "utf16")), name);
        }
    }

    // ------------------------------------------------------------- links and payloads

    [Fact]
    public void LinkParsingReportsTheVectorReasonForEveryCandidate()
    {
        foreach (JsonElement entry in Entries("linkCandidates").EnumerateArray())
        {
            string name = NameOf(entry);
            string link = TextOf(entry, "link");
            string expected = TextOf(entry.GetProperty("reason"));
            long nowEpochMs = entry.GetProperty("nowEpochMs").GetInt64();
            PairingLinkResult result = PairingLink.Parse(link, nowEpochMs);
            string actual = result.Succeeded ? "ok" : result.Reason!;
            Assert.True(expected == actual, name + " expected " + expected + " but got " + actual);
        }
    }

    [Fact]
    public void PayloadDecodingReportsTheVectorReasonAndReadsTheSameValue()
    {
        foreach (JsonElement entry in Entries("payloadCandidates").EnumerateArray())
        {
            string name = NameOf(entry);
            string field = TextOf(entry.GetProperty("field"));
            string json = TextOf(entry.GetProperty("json"));
            string expectedReason = TextOf(entry.GetProperty("reason"));

            PairingPayload? payload;
            try
            {
                payload = PairingPayloadCodec.Deserialize(json);
            }
            catch (SyncContractException exception)
            {
                Assert.True(expectedReason == exception.Reason, name + " expected " + expectedReason + " but got " + exception.Reason);
                payload = null;
            }

            if (payload is null)
            {
                continue;
            }

            Assert.True(expectedReason == "ok", name + " parsed but the vector wanted " + expectedReason);
            string? afterRead = NullableTextOf(entry, "afterRead");
            if (afterRead is null)
            {
                continue;
            }

            Assert.True(afterRead == ReadField(payload, field), name + " (" + field + ")");
        }
    }

    [Fact]
    public void DocumentsWithALoneSurrogateAreRefusedAsMalformedJson()
    {
        foreach (JsonElement entry in Entries("loneSurrogateDocuments").EnumerateArray())
        {
            string name = NameOf(entry);
            string json = TextOf(entry.GetProperty("json"));
            string expected = TextOf(entry.GetProperty("reason"));

            string actual;
            try
            {
                PairingPayloadCodec.Deserialize(json);
                actual = "ok";
            }
            catch (SyncContractException exception)
            {
                actual = exception.Reason;
            }

            Assert.True(expected == actual, name + " expected " + expected + " but got " + actual);
            Assert.True(expected != PairingReasons.MalformedJson || actual == PairingReasons.MalformedJson, name + " (stable code)");
        }
    }

    private static string ReadField(PairingPayload payload, string field) => field switch
    {
        "deviceId" => payload.DeviceId,
        "ephemeralUrl" => payload.EphemeralUrl,
        "challenge" => payload.Challenge,
        "publicKeyFingerprint" => payload.PublicKeyFingerprint,
        _ => throw new ArgumentOutOfRangeException(nameof(field), field, "unknown vector field"),
    };
}
