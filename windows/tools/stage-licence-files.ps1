#Requires -Version 7.0
<#
.SYNOPSIS
    Stage the licence, notice and inventory files into a published tree.

.DESCRIPTION
    windows-ci.yml runs this straight after "Portable publish (Release)" and the smoke check
    asserts the staged files exist. Without it a release-shaped build ships with zero licence or
    notice text - the compliance gap recorded in windows/docs/licensing/SBOM.md section 4.1 and
    windows/docs/licensing/PACKAGING.md section 6 blocker 2.

    The set below is fixed and every source file is tracked in this repository. A missing source
    is a hard error (exit 1) rather than a silently smaller package. The generated MANIFEST.txt
    records the digest and size of every staged file, so the package describes its own contents.

    Verbatim LGPL/GPL licence texts are deliberately not part of the set: whether this project
    vendors them belongs to the licence decision (windows/docs/licensing/LICENCE-DECISION.md).

.PARAMETER RepoRoot
    Repository root. Default: two levels above this script (windows/tools/..).

.PARAMETER TargetDir
    The published tree (e.g. windows/artifacts/portable). A relative path resolves against
    RepoRoot. The script refuses to run when the tree is absent - publish first, then stage.

.PARAMETER SubDirectory
    Directory inside the tree that receives the files. Default: licences.

.EXAMPLE
    pwsh -NoProfile -File windows/tools/stage-licence-files.ps1 -TargetDir windows/artifacts/portable
.NOTES
    Exit codes: 0 = every file staged, 1 = a source is missing or the tree is absent.
#>
[CmdletBinding()]
param(
    [string] $RepoRoot,
    [string] $TargetDir,
    [string] $SubDirectory = "licences"
)

$ErrorActionPreference = "Stop"

if (-not $RepoRoot) { $RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot) }
if (-not (Test-Path -LiteralPath $RepoRoot)) { throw ("repository root not found: " + $RepoRoot) }
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path

if (-not $TargetDir) { throw "TargetDir is required: pass the published tree, e.g. -TargetDir windows/artifacts/portable" }
if (-not [System.IO.Path]::IsPathRooted($TargetDir)) { $TargetDir = Join-Path $RepoRoot $TargetDir }
if (-not (Test-Path -LiteralPath $TargetDir)) { throw ("the publish output is absent at " + $TargetDir + " - publish first, then stage") }
$targetRoot = Join-Path ([System.IO.Path]::GetFullPath($TargetDir)) $SubDirectory

# staged name -> tracked source. Both notices documents ship: the short one is the human summary
# referenced by PACKAGING.md, the full one carries the generated per-package table.
$files = [ordered]@{
    "THIRD-PARTY-NOTICES.md"      = "windows/THIRD-PARTY-NOTICES.md"
    "THIRD-PARTY-NOTICES-FULL.md" = "windows/docs/THIRD-PARTY-NOTICES.md"
    "LGPL-COMPLIANCE.md"          = "windows/docs/LGPL-COMPLIANCE.md"
    "LGPL-ENGINE-SWITCH.md"       = "windows/docs/LGPL-ENGINE-SWITCH.md"
    "component-licences.txt"      = "windows/engine/lgpl/component-licences.txt"
    "sbom.cdx.json"               = "windows/docs/sbom-windows.cdx.json"
}

[System.IO.Directory]::CreateDirectory($targetRoot) | Out-Null
$rows = @()
foreach ($name in $files.Keys) {
    $source = Join-Path $RepoRoot ($files[$name] -replace "/", [string][System.IO.Path]::DirectorySeparatorChar)
    if (-not (Test-Path -LiteralPath $source)) { throw ("missing licence source: " + $files[$name] + " - the package must not ship without it") }
    $destination = Join-Path $targetRoot $name
    Copy-Item -LiteralPath $source -Destination $destination -Force
    $hash = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash.ToLowerInvariant()
    $bytes = (Get-Item -LiteralPath $destination).Length
    $rows += ([string]$hash + " " + [string]$bytes + " " + $files[$name] + " -> " + $SubDirectory + "/" + $name)
}
$rows = @($rows | Sort-Object)

$manifest = Join-Path $targetRoot "MANIFEST.txt"
$header = @(
    "MediaHub portable package - licence and notice inventory"
    "Generated by windows/tools/stage-licence-files.ps1 (W40)."
    "Each line is sha256, size in bytes, the tracked source and the name in this directory."
    "The package ships these files so it can be read without the repository. Verbatim LGPL/GPL"
    "licence texts are not vendored yet (see windows/docs/licensing/LICENCE-DECISION.md)."
    ""
)
[System.IO.File]::WriteAllLines($manifest, ($header + $rows), (New-Object System.Text.UTF8Encoding($false)))

Write-Output ("staged " + $rows.Count + " licence/notice file(s) into " + $targetRoot)
foreach ($row in $rows) { Write-Output ("  " + $row) }
exit 0
